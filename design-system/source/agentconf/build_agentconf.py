#!/usr/bin/env python3
"""Compile rules/frag/*.yaml -> rules/rules.yaml, rules/sheets/*.md, tokens/tokens.json (DTCG),
reference/*.md, history/normative-history.yaml, INDEX.md, traceability report. Run from project root."""
import yaml, json, re, glob, os, collections, sys
R=os.path.abspath(os.path.join(os.path.dirname(__file__),'..','..'))
os.chdir(R)
ID=re.compile(r'^[A-Z][A-Z0-9]{1,7}-[0-9]{3,4}$')
KEYS=['id','statement','scope','check_type','test','status','replaced_by','history_ref']
rules=[];hist=[]
for f in sorted(glob.glob('rules/frag/batch*.yaml')):
    if f.endswith('.history.yaml'): hist+= (yaml.safe_load(open(f, encoding='utf-8')) or []) ; continue
    rules+=yaml.safe_load(open(f, encoding='utf-8'))
ids=collections.Counter(r['id'] for r in rules)
errs=[]
for r in rules:
    if ids[r['id']]>1: errs.append('dup '+r['id'])
    if not ID.match(r['id']): errs.append('badid '+r['id'])
    if not re.search(r'\b(shall|should|SHALL|SHOULD|MUST|MUST NOT|SHOULD NOT)\b',r['statement']): errs.append('no-keyword '+r['id'])
    if r.get('check_type') not in ('lint','ast','dom','visual','judgement'): errs.append('check '+r['id'])
    if re.search(r'DR-\d|\b20\d\d\b|\bv?\d+\.\d+\.\d+\b',r['statement']): errs.append('history-in-statement '+r['id'])
    r.setdefault('status','active'); r.setdefault('replaced_by',None); r.setdefault('history_ref',None)
order=lambda r:(r['id'].split('-')[0],int(r['id'].split('-')[1]))
rules.sort(key=order)
os.makedirs('rules/sheets',exist_ok=True)
out=[{k:r.get(k) for k in KEYS} for r in rules]
open('rules/rules.yaml','w',encoding='utf-8').write('# GENERATED by source/agentconf/build_agentconf.py from rules/frag/. Edit the fragments, not this file.\n# Schema: rules/rules.schema.yaml\n'+yaml.safe_dump(out,sort_keys=False,allow_unicode=True,width=100))
by=collections.defaultdict(list)
for r in rules: by[r['id'].split('-')[0]].append(r)
for p,rs in by.items():
    with open(f'rules/sheets/{p}.md','w',encoding='utf-8') as f:
        f.write(f'# {p} rules (generated)\n\n| ID | Rule | Check | Test |\n|---|---|---|---|\n')
        for r in rs: f.write('| %s | %s | %s | %s |\n'%(r['id'],r['statement'].replace('|','\\|'),r['check_type'],str(r['test']).replace('|','\\|').replace('\n',' ')))
# DTCG
t=json.load(open('tokens.json',encoding='utf-8'));D={}
def put(path,val,desc,typ,ext=None):
    n=D
    for p in path[:-1]: n=n.setdefault(p,{})
    o={'$value':val,'$type':typ,'$description':desc}
    if ext: o['$extensions']={'com.songnodes':ext}
    n[path[-1]]=o
for k in t['color']['tokens']:
    v=k['value']
    put(['color',k['name']],v['dark'] if isinstance(v,dict) else v,k.get('usage',''),'color',{'modes':v} if isinstance(v,dict) else None)
for sec,typ in [('spacing','dimension'),('radius','dimension'),('size','dimension'),('zIndex','number'),('duration','duration'),('easing','cubicBezier'),('breakpoint','dimension'),('opacity','number'),('shadow','shadow')]:
    for k in t[sec]['tokens']:
        v=k['value']; modes=None
        if isinstance(v,dict): modes=v; v=v['dark']
        if typ=='cubicBezier':
            m=re.findall(r'[\d.]+',v); v=[float(x) for x in m] if len(m)==4 else v
        put([sec,k['name']],v,k.get('usage',''),typ,{'modes':modes} if modes else None)
for g in t['type']['groups']:
    for s in g['styles']:
        put(['typography',s['name']],{x:s[x] for x in s if x!='name'},s.get('usage',''),'typography')
# 1.11.0: LiveChange family (durations, easing, counts, sizes)
for k in t.get('live',{}).get('tokens',[]):
    v=k['value']; vs=str(v)
    if vs.startswith('cubic-bezier'): typ='cubicBezier'; v=[float(x) for x in re.findall(r'[\d.]+',vs)]
    elif vs.endswith('ms'): typ='duration'
    elif vs.endswith('px') or vs.endswith('rem'): typ='dimension'
    else: typ='number'
    put(['live',k['name']],v,k.get('usage',''),typ)
for n,v in t['type']['families'].items(): put(['fontFamily',n],v,'','fontFamily')
os.makedirs('tokens',exist_ok=True)
json.dump({'$description':'SongNodes tokens, W3C DTCG. GENERATED from tokens.json by build_agentconf.py. Modes in $extensions.com.songnodes.modes; $value is the dark theme.',**D},open('tokens/tokens.json','w',encoding='utf-8'),indent=1)
# reference
os.makedirs('reference',exist_ok=True)
with open('reference/tokens.md','w',encoding='utf-8') as f:
    f.write('# Token reference (generated)\n\n| Token | Dark value | Description |\n|---|---|---|\n')
    def walk(n,p):
        for k,v in n.items():
            if k.startswith('$'): continue
            if '$value' in v: f.write('| %s | `%s` | %s |\n'%('.'.join(p+[k]),json.dumps(v['$value']) if not isinstance(v['$value'],str) else v['$value'],v['$description'].replace('|','/')))
            else: walk(v,p+[k])
    walk(D,[])
with open('reference/components.md','w',encoding='utf-8') as f:
    f.write('# Component reference (generated)\n\n| Component | README | Preview |\n|---|---|---|\n')
    for c in sorted(os.listdir('components')):
        if os.path.isdir('components/'+c): f.write(f'| {c} | components/{c}/README.md | components/{c}/preview.html |\n')
# traceability
cov=collections.OrderedDict()
for f in sorted(glob.glob('rules/frag/*.coverage.txt')): cov[os.path.basename(f)]=open(f,encoding='utf-8').read()
unm=sum(len(re.findall(r'^\s*[-*]\s',c,re.M)) for c in cov.values() if 'unmapped' in c.lower())
src=collections.Counter()
for r in rules:
    for s in re.split(r';\s*',str(r.get('source',''))): src[s.split(':')[0]]+=1
open('rules/TRACEABILITY.md','w',encoding='utf-8').write('# Traceability (generated)\n\n| Source file | Rules citing it |\n|---|---|\n'+''.join(f'| {k} | {v} |\n' for k,v in sorted(src.items()))+f'\nTotal rules: {len(rules)}\nSchema/format errors: {len(errs)}\nHistory items segregated: {len(hist)}\n')
yaml.safe_dump(hist,open('history/normative-history.yaml','w',encoding='utf-8'),allow_unicode=True,sort_keys=False)
# keep source in a separate archive file (not in rules.yaml per schema)
yaml.safe_dump({r['id']:r.get('source') for r in rules},open('rules/sources.yaml','w',encoding='utf-8'),sort_keys=False)
print(len(rules),'rules;',len(errs),'errors');print('\n'.join(errs[:40]))
