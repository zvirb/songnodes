#!/usr/bin/env python3
"""Build docs/design-system/reference.standalone.html: reference.html with the design system inlined.

Run from the repo root:  python3 docs/design-system/build_standalone.py
Stdlib only. Inlines design-system/tokens.css, components/bundle.css and components/bundle.js,
and embeds the four fonts in design-system/fonts/ as base64 data URIs in the @font-face rules,
so the file works offline with no other files. This is the copy published as a shareable artifact.

Inline-safety: a stylesheet must not contain "</style" and a classic script must not contain
"</script" or "<!--"; those sequences are rewritten as "<\\/style", "<\\/script" and "\\x3C!--"
(and "<\\!--" in CSS), which the CSS and JS parsers read back as the same text.
"""
import base64
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
DS = ROOT / "design-system"
SRC = HERE / "reference.html"
OUT = HERE / "reference.standalone.html"


def read(p):
    return p.read_text(encoding="utf-8")


def safe_css(css):
    css = re.sub(r"</(style)", r"<\\/\1", css, flags=re.I)
    return css.replace("<!--", "<\\!--")


def safe_js(js):
    js = re.sub(r"</(script)", r"<\\/\1", js, flags=re.I)
    return js.replace("<!--", "\\x3C!--")


def embed_fonts(css):
    def repl(m):
        rel = m.group(1)
        f = DS / rel
        if not f.exists():
            sys.exit("missing font: %s" % f)
        b64 = base64.b64encode(f.read_bytes()).decode("ascii")
        return 'url("data:font/woff2;base64,%s")' % b64
    css, n = re.subn(r'url\("(fonts/[^"]+\.woff2)"\)', repl, css)
    return css, n


def main():
    page = read(SRC)
    tokens, n_fonts = embed_fonts(read(DS / "tokens.css"))
    bundle_css = read(DS / "components" / "bundle.css")
    bundle_js = read(DS / "components" / "bundle.js")

    links = {
        '<link rel="stylesheet" href="../../design-system/tokens.css">':
            "<style>/* design-system/tokens.css (fonts embedded) */\n%s\n</style>" % safe_css(tokens),
        '<link rel="stylesheet" href="../../design-system/components/bundle.css">':
            "<style>/* design-system/components/bundle.css */\n%s\n</style>" % safe_css(bundle_css),
        '<script src="../../design-system/components/bundle.js"></script>':
            "<script>/* design-system/components/bundle.js */\n%s\n</script>" % safe_js(bundle_js),
    }
    for tag, inline in links.items():
        if page.count(tag) != 1:
            sys.exit("reference.html: expected exactly one %s" % tag)
        page = page.replace(tag, inline)  # str.replace: no regex, backslashes kept as is
    page = page.replace("<title>Design system reference · SongNodes</title>",
                        "<title>Design system reference · SongNodes</title>\n<!-- Standalone build of docs/design-system/reference.html: generated by build_standalone.py, do not edit -->", 1)
    OUT.write_text(page, encoding="utf-8")
    print("%s: %d bytes, %d fonts embedded" % (OUT.relative_to(ROOT), OUT.stat().st_size, n_fonts))
    if n_fonts != 4:
        sys.exit("expected 4 @font-face urls, embedded %d" % n_fonts)


if __name__ == "__main__":
    main()
